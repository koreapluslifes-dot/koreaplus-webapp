#!/usr/bin/env node
/* F3 — build-time discography snapshot (Apple iTunes Search/Lookup, no key).
 *
 *   node tools/gen-kpop-discog.cjs
 *
 * Two passes per act:
 *   1. search  → resolve an Apple artistId for the act's English name
 *   2. lookup  → that artist's albums (title, release date, 300px artwork)
 *
 * VERIFICATION GATE (required): Apple's search regularly returns the WRONG act
 * for K-pop queries (a live probe had "BLACKPINK" resolve to TWICE). Every
 * resolved artistId is therefore re-checked against the expected name, and an
 * act whose artistName does not match is DROPPED rather than shipped wrong.
 *
 * Output kpop-discog.js:
 *   window.KPOP_DISCOG = { blackpink: { asOf, albums:[{title,year,date,art}] } }
 *
 * Feeds both the modal Discography tab (F3) and the "Recent Releases" strip
 * (F2), which filters these releaseDates client-side. Re-run to refresh.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'kpop-discog.js');
const UA = 'KoreaPlusBot/1.0 (https://koreaplus-lifes.com)';
const GAP = 3200;            // iTunes allows ~20 calls/min — stay well under
const MAX_ALBUMS = 24;

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function getJSON(url) {
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error('HTTP ' + res.status);
  return res.json();          // iTunes sends text/javascript; fetch still parses
}

function loadRoster() {
  const ctx = { window: {} };
  vm.createContext(ctx);
  vm.runInContext(fs.readFileSync(path.join(ROOT, 'kpop-data.js'), 'utf8'), ctx);
  return ctx.window.KPOP_ROSTER || ctx.KPOP_ROSTER || [];
}

// Loose name equality: case/space/punctuation-insensitive, so "G-IDLE" == "(G)I-DLE".
const norm = (s) => String(s || '').toLowerCase().replace(/[^a-z0-9]/g, '');
function nameMatches(expected, got) {
  const a = norm(expected), b = norm(got);
  if (!a || !b) return false;
  return a === b || b.includes(a) || a.includes(b);
}

async function resolveArtist(name) {
  const url = 'https://itunes.apple.com/search?media=music&entity=musicArtist&limit=5&term='
    + encodeURIComponent(name);
  const d = await getJSON(url);
  const hits = d.results || [];
  const hit = hits.find((h) => nameMatches(name, h.artistName)) || null;
  return hit ? { id: hit.artistId, name: hit.artistName } : { id: null, name: hits[0] && hits[0].artistName };
}

async function albums(artistId) {
  const url = `https://itunes.apple.com/lookup?id=${artistId}&entity=album&sort=recent&limit=${MAX_ALBUMS + 1}`;
  const d = await getJSON(url);
  return (d.results || [])
    .filter((r) => r.wrapperType === 'collection' && r.collectionName)
    .map((r) => ({
      title: r.collectionName,
      date: (r.releaseDate || '').slice(0, 10),
      year: (r.releaseDate || '').slice(0, 4),
      art: String(r.artworkUrl100 || '').replace('100x100', '300x300'),
    }))
    .filter((x) => x.date)
    .sort((a, b) => (a.date < b.date ? 1 : -1))
    .slice(0, MAX_ALBUMS);
}

(async () => {
  const roster = loadRoster();
  const asOf = new Date().toISOString().slice(0, 10);
  const out = {};
  const kept = [], dropped = [];
  for (const a of roster) {
    try {
      const r = await resolveArtist(a.nameEn);
      await sleep(GAP);
      if (!r.id) { dropped.push(`${a.id}(no match; got "${r.name || '-'}")`); continue; }
      const list = await albums(r.id);
      await sleep(GAP);
      if (!list.length) { dropped.push(`${a.id}(0 albums)`); continue; }
      out[a.id] = { artistId: r.id, artistName: r.name, asOf, albums: list };
      kept.push(`${a.id}:${list.length}`);
    } catch (e) {
      dropped.push(`${a.id}(${e.message})`);
      await sleep(GAP);
    }
  }
  const body = '/* GENERATED by tools/gen-kpop-discog.cjs — do not edit by hand.\n'
    + `   Albums from the Apple iTunes API, as of ${asOf}. Acts whose artistId could\n`
    + '   not be verified against the expected name are intentionally absent. */\n'
    + 'window.KPOP_DISCOG = ' + JSON.stringify(out, null, 1) + ';\n';
  fs.writeFileSync(OUT, body);
  console.log(`[kpop-discog] kept ${kept.length}/${roster.length} → kpop-discog.js (asOf ${asOf})`);
  console.log('  kept:', kept.join(' '));
  console.log('  dropped:', dropped.join(' ') || '(none)');
})();
