#!/usr/bin/env node
/* F1 — build-time artist photo snapshot (Wikidata P18 → Wikimedia Commons).
 *
 *   node tools/gen-kpop-images.cjs
 *
 * For every ROSTER act that has a wikidataId, resolves the P18 "image" claim,
 * then asks Commons for a thumbnail URL plus the licence metadata (author +
 * licence short name). Writes kpop-images.js:
 *
 *   window.KPOP_IMAGES = { newjeans: { src, artist, license, page }, ... }
 *
 * Only entries with a usable image AND a recognised free licence are kept —
 * an act without a verified licence falls back to its emoji at render time,
 * which is better than shipping an attribution-less photo. No key required.
 * Re-run whenever the roster changes; the deployed artifact is a static file.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'kpop-images.js');
const UA = 'KoreaPlusBot/1.0 (https://koreaplus-lifes.com; contact via site)';
const THUMB_W = 480;

// Free licences we are willing to ship (with attribution rendered in the UI).
const OK_LICENCE = /^(cc[ -]?by([ -]sa)?([ -]?\d(\.\d)?)?|cc0|public domain|pd)/i;

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function getJSON(url) {
  const res = await fetch(url, { headers: { 'User-Agent': UA, Accept: 'application/json' } });
  if (!res.ok) throw new Error('HTTP ' + res.status);
  return res.json();
}

function loadRoster() {
  const ctx = { window: {} };
  vm.createContext(ctx);
  vm.runInContext(fs.readFileSync(path.join(ROOT, 'kpop-data.js'), 'utf8'), ctx);
  return ctx.window.KPOP_ROSTER || ctx.KPOP_ROSTER || [];
}

// Wikidata entity → P18 commons filename
async function p18(qid) {
  const d = await getJSON(`https://www.wikidata.org/wiki/Special:EntityData/${qid}.json`);
  const ent = d.entities && d.entities[qid];
  const claim = ent && ent.claims && ent.claims.P18 && ent.claims.P18[0];
  return (claim && claim.mainsnak && claim.mainsnak.datavalue && claim.mainsnak.datavalue.value) || null;
}

// Commons filename → { src, artist, license, page }
async function commons(file) {
  const url = 'https://commons.wikimedia.org/w/api.php?action=query&format=json&origin=*'
    + '&prop=imageinfo&iiprop=url|extmetadata&iiurlwidth=' + THUMB_W
    + '&titles=' + encodeURIComponent('File:' + file);
  const d = await getJSON(url);
  const pages = (d.query && d.query.pages) || {};
  const page = Object.values(pages)[0];
  const ii = page && page.imageinfo && page.imageinfo[0];
  if (!ii) return null;
  const meta = ii.extmetadata || {};
  const strip = (h) => String(h || '').replace(/<[^>]*>/g, '').replace(/\s+/g, ' ').trim();
  return {
    src: ii.thumburl || ii.url,
    artist: strip(meta.Artist && meta.Artist.value) || 'Wikimedia Commons',
    license: strip(meta.LicenseShortName && meta.LicenseShortName.value),
    page: ii.descriptionurl || '',
  };
}

(async () => {
  const roster = loadRoster();
  const out = {};
  const kept = [], skipped = [];
  for (const a of roster) {
    if (!a.wikidataId) { skipped.push(`${a.id}(no wikidataId)`); continue; }
    try {
      const file = await p18(a.wikidataId);
      await sleep(1100);
      if (!file) { skipped.push(`${a.id}(no P18)`); continue; }
      const info = await commons(file);
      await sleep(1100);
      if (!info || !info.src) { skipped.push(`${a.id}(no imageinfo)`); continue; }
      if (!OK_LICENCE.test(info.license || '')) { skipped.push(`${a.id}(licence:${info.license || 'unknown'})`); continue; }
      out[a.id] = info;
      kept.push(`${a.id}[${info.license}]`);
    } catch (e) {
      skipped.push(`${a.id}(${e.message})`);
      await sleep(1100);
    }
  }
  const body = '/* GENERATED by tools/gen-kpop-images.cjs — do not edit by hand.\n'
    + `   Artist photos from Wikidata P18 / Wikimedia Commons, as of ${new Date().toISOString().slice(0, 10)}.\n`
    + '   Every entry carries author + licence; the UI MUST render that credit. */\n'
    + 'window.KPOP_IMAGES = ' + JSON.stringify(out, null, 1) + ';\n';
  fs.writeFileSync(OUT, body);
  console.log(`[kpop-images] kept ${kept.length}/${roster.length} → kpop-images.js`);
  console.log('  kept:', kept.join(' '));
  console.log('  skipped:', skipped.join(' ') || '(none)');
})();
